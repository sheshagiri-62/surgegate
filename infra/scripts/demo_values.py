"""Write the demo Helm values from `terraform output` (Day 10 Task 4).

The demo IDs (Cognito pool + clients, CloudFront domain, Redis endpoint, ALB / target-group
dimensions, the load-test issuer) exist only after the first demo apply, so the demo values
files are GENERATED, never edited by hand:

    terraform -chdir=infra/envs/demo output -json > demo-out.json
    python infra/scripts/demo_values.py demo-out.json
    # -> deploy/helm/{booking-api,mock-pay,organiser}/values-demo.yaml; commit + PR; Argo syncs

Each file only OVERRIDES the chart's values.yaml (dev), so the image tags bumped by CI in
values.yaml apply to demo too. Without an output file it writes the placeholders that are
committed until the first apply (`python demo_values.py`).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ACCOUNT = "968077439619"
REGION = "ap-south-1"
NAME = "surgegate-demo"
PREFIX = "surgegate/demo"
PLACEHOLDER = "set-by-demo_values.py-after-the-first-apply"


def outputs(path: str | None) -> dict:
    if not path:
        return {}
    return {k: v.get("value") for k, v in json.loads(Path(path).read_text()).items()}


def get(o: dict, key: str, sub: str | None = None) -> str:
    v = o.get(key)
    if sub is not None and isinstance(v, dict):
        v = v.get(sub)
    return str(v) if v else PLACEHOLDER


HEADER = (
    "# GENERATED by infra/scripts/demo_values.py from `terraform output` (demo). Do not edit by\n"
    "# hand: change the script and re-run it. Overrides values.yaml (dev) for the demo cluster.\n"
)


def booking_api(o: dict) -> str:
    cf = get(o, "api_url").rstrip("/")
    issuer, audience = o.get("loadtest_issuer") or "", o.get("loadtest_audience") or ""
    return (
        HEADER
        + f"""
# 50k-fan load test: more pods, real CPU requests so the HPA means something on demo nodes.
autoscaling:
  minReplicas: 3
  maxReplicas: 8 # x 10 DB connections (pool 5 + overflow 5) + workers < db.t4g.micro ~112
  targetCPU: 60
prescale:
  minReplicas: 6

resources:
  requests:
    cpu: 250m
    memory: 128Mi
  limits:
    memory: 384Mi

targetGroupBinding:
  targetGroupName: {NAME}-booking-api

database:
  instanceId: {NAME}-pg

auth:
  userPoolId: {get(o, "cognito_user_pool_id")}
  clientIds:
    - {get(o, "cognito_client_ids", "buyer_web")} # buyer-web
    - {get(o, "cognito_client_ids", "organiser_web")} # organiser-web
    - {get(o, "cognito_client_ids", "test")} # test (load-test organiser script)
  # Load-test window ONLY (enable_loadtest): empty again after the test (re-run this script).
  loadtestIssuer:
    issuer: "{issuer}"
    audience: "{audience}"

redis:
  host: {get(o, "redis_primary_endpoint")}
  authSecretId: {PREFIX}/data/redis-auth

cors:
  allowOrigins:
    - {cf}

queue:
  table: {NAME}-queue

bookingPass:
  required: true
  secretId: {PREFIX}/queue/pass-key

saleEvents:
  stream: {NAME}-sale-events

holdTimer:
  arn: arn:aws:states:{REGION}:{ACCOUNT}:stateMachine:{NAME}-hold-timer

payments:
  provider: mock
  secretId: {PREFIX}/data/razorpay
  mock:
    apiUrl: http://mock-pay.mock-pay.svc.cluster.local
    checkoutBase: {cf}
  returnOrigins:
    - {cf}
  queueUrl: https://sqs.{REGION}.amazonaws.com/{ACCOUNT}/{NAME}-payments

tickets:
  bucket: {get(o, "data_buckets", "tickets")}
  keySecretId: {PREFIX}/data/ticket-key

live:
  keySecretId: {PREFIX}/events/live-key
  wsUrl: {get(o, "live_ws_url")}

environment: demo
tracing:
  enabled: true
  sampleRatio: "0.01" # 1%: a 50k run stays inside X-Ray's free 100k traces/month

rollout:
  analysis:
    loadBalancer: {get(o, "alb_arn_suffix")}
    targetGroup: {get(o, "target_group_arn_suffix")}
"""
    )


def mock_pay(o: dict) -> str:
    cf = get(o, "api_url").rstrip("/")
    return (
        HEADER
        + f"""
targetGroupBinding:
  targetGroupName: {NAME}-mock-pay

secretId: {PREFIX}/data/razorpay

webhookUrl: {cf}/webhooks/razorpay

callbackAllowOrigins:
  - {cf}
"""
    )


def organiser(o: dict) -> str:
    return (
        HEADER
        + f"""
targetGroupBinding:
  targetGroupName: {NAME}-organiser

cognito:
  region: {REGION}
  clientId: {get(o, "cognito_client_ids", "organiser_web")}
"""
    )


def main() -> None:
    o = outputs(sys.argv[1] if len(sys.argv) > 1 else None)
    for chart, render in (
        ("booking-api", booking_api),
        ("mock-pay", mock_pay),
        ("organiser", organiser),
    ):
        path = ROOT / "deploy" / "helm" / chart / "values-demo.yaml"
        path.write_text(render(o), encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    missing = [
        k for k in ("api_url", "cognito_user_pool_id", "redis_primary_endpoint") if not o.get(k)
    ]
    if missing:
        print(f"placeholders left (no output yet): {', '.join(missing)}")


if __name__ == "__main__":
    main()
